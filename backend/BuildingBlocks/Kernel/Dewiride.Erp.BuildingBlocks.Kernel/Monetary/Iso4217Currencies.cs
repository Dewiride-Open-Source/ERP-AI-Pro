    private static readonly FrozenDictionary<string, Currency> ByCode = Entries.ToFrozenDictionary(currency => currency.Code, StringComparer.Ordinal);

    private static readonly ReadOnlyCollection<Currency> ReadOnlyEntries = Array.AsReadOnly(Entries);

    public static IReadOnlyList<Currency> All => ReadOnlyEntries;

    public static Currency Find(string code) => ByCode[code];

    public static bool TryFind(string? code, out Currency currency)
    {
        if (code is not null && ByCode.TryGetValue(code, out currency))
        {
            return true;
        }

        currency = default;
        return false;
    }
